import { chromium } from 'playwright';
import { createServer } from '../server.js';
import os from 'node:os'; import fs from 'node:fs';
const file = process.argv[2];
const srv = createServer('docs', {'/fixtures/': 'tests/fixtures', '/dl/': os.homedir() + '/Downloads'});
await new Promise(r => srv.listen(0, '127.0.0.1', r));
const b = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const p = await (await b.newContext({ serviceWorkers: 'block', viewport: { width: 1400, height: 1000 } })).newPage();
p.on('pageerror', e => console.log('PAGEERROR', e.message));
await p.goto(`http://127.0.0.1:${srv.address().port}/index.html?nosw`);
const t = Date.now();
await p.setInputFiles('#modelInput', [os.homedir() + '/Downloads/' + file]);
await p.waitForFunction(() => /Character loaded|rror/.test(document.getElementById('statusText').textContent), null, { timeout: 120000 }).catch(() => console.log('LOAD TIMEOUT'));
console.log(file, 'loaded in', ((Date.now() - t) / 1000).toFixed(1) + 's:', await p.evaluate(() => document.getElementById('statusText').textContent));
console.log(await p.evaluate(() => document.getElementById('log').innerText.slice(-600)));
await p.waitForTimeout(800); await p.locator('#viewer').screenshot({ path: `/tmp/q0-${file}.png` });
const t2 = Date.now();
await p.evaluate(async () => { const m = await (await fetch('/fixtures/mocap-33s.bvh')).arrayBuffer(); const f = new File([m], 'mocap-33s.bvh'); const dt = new DataTransfer(); dt.items.add(f); const i = document.getElementById('motionInput'); i.files = dt.files; i.dispatchEvent(new Event('change')); });
await p.waitForFunction(() => window.__webcli_result, null, { timeout: 180000 }).catch(() => console.log('BAKE TIMEOUT'));
console.log('baked in', ((Date.now() - t2) / 1000).toFixed(1) + 's', await p.evaluate(() => JSON.stringify(window.__webcli_result && { ok: window.__webcli_result.ok, err: window.__webcli_result.error, size: window.__webcli_result.artifact?.size })));
await p.evaluate(() => document.getElementById('btnPlay').click());
await p.evaluate(() => { const s = document.getElementById('scrub'); s.value = 250; s.dispatchEvent(new Event('input')); });
await p.waitForTimeout(500);
await p.locator('#viewer').screenshot({ path: `/tmp/q-${file}.png` });
await b.close(); srv.close(); process.exit(0);
